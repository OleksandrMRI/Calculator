/**
 * This class contains string and char values of unary minus
 * although numeric string value of unary string multiplicator
 * (the number that can be used to represent unary minus as
 * multiplication)
 */
public class UnaryMinus {
    /**
     * string value of unary minus
     */
    public static final String VALUE = "-";

    /**
     * char value of unary minus
     */
    public static final char CHAR_VALUE = '-';

    /**
     * numeric string value of unary string multiplicator
     * (the number that can be used to represent unary minus as
     *  multiplication)
     */
    public static final String UNARY_MINUS_MULTIPLICATOR = "-1";
}
